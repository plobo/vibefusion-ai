export function buildEnvelopeCases() {
  return {
    description:
      "Generated by backend/scripts/generate-fixtures.ts from backend/src/fusion/envelope.ts. Do not edit by hand.",
    tolerance: 1e-4,
    cases: ENVELOPE_PLANS.map((c) => ({
      name: c.name,
      plan: c.plan,
      assetDurationsMs: c.assetDurationsMs,
      masterGain: round(masterGain(c.plan)),
      pan: Object.fromEntries(c.plan.layers.map((l) => [l.id, panGains(l.pan).map(round)])),
      samples: c.times.map((t) => ({
        tMs: t,
        duckWeight: round(duckWeight(c.plan, t)),
        gains: Object.fromEntries(c.plan.layers.map((l) => [l.id, round(layerGain(c.plan, l, t))])),
        sourcePositionsMs: Object.fromEntries(
          c.plan.layers.map((l) => [l.id, sourcePositionMs(l, c.assetDurationsMs[l.assetId] ?? 0, t)]),
        ),
      })),
    })),
  };
}
